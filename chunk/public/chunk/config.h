// Rechunk rebuild suppresses the OMPT parallel-end finalize. The rebuild
// (array_chunk_base.h) drives the deferred write path inside its OWN parallel region; its
// on_parallel_end would flush + compress MID-REBUILD, before every new chunk is consistently
// written (corrupting grow regions spanning several old chunks). rechunk_to flushes
// afterwards at a quiescent point.
// WRITTEN by the master only, outside any region (release). READ by the OMPT callbacks
// (acquire): on_parallel_end on the master, on_sync_region on EVERY team thread. The fork and
// closing barrier order the reads inside the region; the one that could cross the master's
// `false` (a worker leaving the closing barrier) is filtered by on_sync_region's early
// return. Atomic so correctness does not rest on that guard.
namespace shrink_array
{
inline std::atomic<bool> g_in_rechunk_rebuild{false};

// Monotonic count of committed rechunk_to() calls (no-op/empty/refused ones do NOT count),
// bumped in ArrayChunkBase::rechunk_to before the rebuild. Process-wide, never reset: a
// harness wanting a per-phase delta snapshots it.
inline unsigned long g_rechunk_count = 0;
} // namespace shrink_array
