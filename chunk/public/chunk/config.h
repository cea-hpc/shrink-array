/**
 * @brief The write/compress handshake's shape (WriteCompressSyncPolicy).
 *
 * @details Two sides must never run together: an element WRITE inside its critical section,
 *          and a COMPRESSOR stealing that chunk's buffer (or a cross-rank flush). Writes are
 *          the hot path; the other side is rare.
 *
 *          - symmetric (false): both sides announce with a seq_cst store and a full fence,
 *            then look at the other. Correct everywhere, but the writer pays `stlr` +
 *            `dmb ish` + `ldar` on AArch64 (`mfence` on x86) on EVERY write, which dominates
 *            write_with_optional_lock_impl.
 *          - asymmetric (true): the writer's announce is a plain store and a COMPILER barrier
 *            only; the rare side, after its own seq_cst announce, calls
 *            membarrier(MEMBARRIER_CMD_PRIVATE_EXPEDITED), a full barrier on every CPU running
 *            a thread of this process. Each writer's store->load pair is then split by that
 *            barrier, or entirely before or after it -- in every case one side sees the other
 *            (as JVM safepoints / .NET FlushProcessWriteBuffers). See announce_write() for the
 *            argument and heavy_barrier() for the call.
 *
 *          Asymmetric is the shape of every build that can (no option): it removes the fence
 *          from every write. It relies on the rare side staying rare: do not send every write
 *          of a rank through the slow path (one announce each) -- membarriers then become a
 *          feedback loop, an order of magnitude slower. Symmetric only on non-Linux (the
 *          syscall) and under ThreadSanitizer (which does not model membarrier). An
 *          asymmetric build falls back to symmetric AT RUN TIME if membarrier registration
 *          fails (kernel < 4.14, seccomp); print_chunk_stats() says which one ran.
 */
#if defined(__linux__) && !defined(CHUNK_TSAN_BUILD)
inline constexpr bool asymmetric_dekker = true;
#else
inline constexpr bool asymmetric_dekker = false;
#endif

