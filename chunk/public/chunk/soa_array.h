#pragma once

/**
 * @file soa_array.h
 * @brief SoaArray<T>: an array of structs stored as one compressed array per
 *        member, generated by C++26 static reflection (cpp26 branch).
 *
 * @details A zero_any::Array<Cell> compresses a chunk only when whole Cells
 *          repeat. In simulation data the members repeat on their own: the
 *          material id is constant over large regions while the density
 *          varies, a flag is mostly false while the coordinates are not.
 *          SoaArray<Cell> keeps one column -- a zero_any::Array of the member's
 *          type by default -- per non-static data member of Cell, found by
 *          reflection, so each member compresses on its own runs:
 *
 *          @code
 *          struct Cell { double rho; double temp; int mat; };
 *
 *          shrink_array::SoaArray<Cell> a(n);   // three columns: double, double, int
 *          a[i].rho  = 2.5;                     // writes column rho only
 *          a[i].temp += 300.0;                  // the compound ops of the column's proxy
 *          Cell c = a.get(i);                   // gathers the three members
 *          a.set(i, c);                         // scatters them
 *          auto& mat = a.column<^^Cell::mat>(); // the zero_any::Array<int> itself:
 *                                               // range operations, stats, mdspan views
 *          @endcode
 *
 *          A member that is itself a struct -- with no operator==, so no
 *          ArrayChunkElement -- or an array is stored part by part, one
 *          column per scalar it holds, and a[i] mirrors it:
 *
 *          @code
 *          struct Vec3 { double x, y, z; };
 *          struct Cell { Vec3 pos; double w[2]; int mat; };   // columns pos.x pos.y pos.z w[0] w[1] mat
 *
 *          shrink_array::SoaArray<Cell> a(n);
 *          a[i].pos.y = 1.0;                                   // column pos.y only
 *          a[i].w[1] += 2.0;
 *          auto& y = a.column<^^Cell::pos, ^^Vec3::y>();      // a column by its path of members
 *          @endcode
 *
 *          A struct that is an ArrayChunkElement stays one column, unless
 *          its member is marked [[=soa::split]]. column_count, column_name(k)
 *          ("pos.y", "w[1]"), column_at<k>() and field<k>(v) (the part of a
 *          T that column k stores) walk the columns by index.
 *
 *          Range operations, member by member (each column keeps its own
 *          semantics: a chunk filled with one value takes it as its
 *          constant): fill_range(a, lo, hi, v), copy_range(a, lo, hi, src)
 *          from structs (the AoS to SoA transposition), their _mt forms
 *          (every thread of a phase on its own range), read_range(a, lo, hi,
 *          out) back into structs; resize(), push_back() forward to every
 *          column.
 *
 *          A member can pick its own storage with an annotation (C++26,
 *          P3394), the other members keeping the array's Column:
 *
 *          @code
 *          namespace sa = shrink_array;
 *          struct Cell {
 *              [[=sa::soa::plain]] double noise;              // a std::vector<double>
 *              [[=sa::soa::column<sa::zero::Array>]] int mat; // a zero::Array<int>
 *              double rho;                                    // the default, zero_any::Array<double>
 *          };
 *          @endcode
 *
 *          soa::plain stores a member that never repeats -- noise, a
 *          coordinate of a moving particle -- with no chunk at all;
 *          soa::column<C> takes any one-parameter template of the member
 *          type (zero::Array, zero_one_value::Array, zero_any::Array, an
 *          alias). On a member stored part by part, the annotation goes to
 *          every part, unless a part carries its own. Other annotations, of
 *          other libraries, are left alone.
 *
 *          a[i] returns SoaArray<Cell>::Ref, an aggregate generated by
 *          reflection whose members carry Cell's names and hold the
 *          columns' write proxies (ElementRef) -- a struct member a nested
 *          aggregate of them, an array member an array: use it as a temporary, as
 *          the array's own a[i] (`auto r = a[i];` then `r.rho = 1;` does not
 *          compile in a check build). The const a[i] returns a Cell.
 *
 *          Every rule of the columns applies unchanged, column by column:
 *          OpenMP phases bracketed (parallel_phase() or OMPT), sequential
 *          points (shrink_to_fit(), forwarded to every column; a column's
 *          own operations through column<M>()), no proxy kept across a
 *          resize or a re-chunk.
 *
 * @note Requirements on T: a class with public non-static data members only
 *       (no base class, no bit-field, no reference member), each of a type an
 *       array of the library accepts (ArrayChunkElement: trivially copyable,
 *       equality-comparable, T{} its first constant), a struct of such
 *       members under the same rules, or an array of either; at most one
 *       storage annotation (soa::plain, soa::column<C>) per member. T itself
 *       need not be equality-comparable.
 *
 * @warning Experimental (until 1.0). C++26 static reflection (GCC 16 -freflection).
 */

