"""Phase 1 (2a, 2b): the correctness checks against each config's oracle."""
import os
import sys
import time

from .. import share
from ..builds import ORACLE_EXE_KEY, ORACLE_MARKER, exe_fingerprint, oracle_dir, purge_oracle, short_config_label
from ..progress import _prog, get_progress_bar
from ..runs import _append_error_now, effective_timeout, repro_line, run_cmd
from ..settings import config_env
from ..term import bold, cyan, green, red


def run_check_phase(args, plan, counter, errors):
    """Generate the missing oracles with each config's vector baseline, then
    run every check binary --reps_check times in its config's oracle directory.

    --pool: the unit is a configuration, claimed as check/<config>: its
    oracle (when it needs one, claimed again as oracle_<config>) then its
    checks, by the same job one configuration after another -- not every
    oracle first, which would hand them all to the first job. Without
    --pool, the order is the one it always was (2a, then 2b)."""
    print(cyan(bold(f"\n🔍 Correctness check — {args.check_threads} threads")))

    if share.active():
        for cfg in args.configs:
            if cfg not in plan.configs_checked:
                continue                  # no check binary: no unit, no oracle needed
            if not share.take("check", cfg, short_config_label(cfg)):
                counter.skip(_check_runs(plan, cfg) + (1 if plan.oracle_needed.get(cfg) else 0))
                continue
            ready = True
            try:
                if plan.oracle_needed.get(cfg):
                    if share.claim_oracle(cfg):
                        ok = False
                        try:
                            # The purge prepare_oracles leaves to the claimer.
                            purge_oracle(oracle_dir(share.oracle_root(args), cfg))
                            ok = _generate_oracle(args, plan, counter, errors, cfg)
                        finally:
                            share.oracle_done(cfg, ok)
                    else:
                        counter.skip(1)
                        ready = share.wait_oracle(cfg, short_config_label(cfg))
            finally:
                share.check_unit_oracle_settled(cfg)
            if not ready:
                _entry = share.oracle_timeout_entry(cfg, short_config_label(cfg))
                print(red("   " + _entry.splitlines()[0]))
                errors.append(_entry)
                _append_error_now(args.errors_log, _entry)
                counter.skip(_check_runs(plan, cfg))
                continue
            _check_config(args, plan, counter, errors, cfg)
        return

    # 2a. Generate the reference of every config that needs one, with
    #     the config's own vector baseline, uncompressed, in its
    #     oracle directory (one run each).
    for cfg_b in plan.configs_checked:
        if not plan.oracle_needed.get(cfg_b):
            continue
        _generate_oracle(args, plan, counter, errors, cfg_b)

    # 2b. Checks for the non-baseline variants, each in its config's
    #     oracle directory.
    for cfg in args.configs:
        _check_config(args, plan, counter, errors, cfg)


def _check_runs(plan, cfg):
    """The check runs of @p cfg the run counter counts (Plan.count_runs)."""
    return plan.reps_check_for(cfg) * sum(1 for (c, _v) in plan.check_exes if c == cfg)


def _generate_oracle(args, plan, counter, errors, cfg_b):
    """2a for one configuration: its vector baseline run in its oracle
    directory, the completeness marker written after a success. True then."""
    exe_b = plan.baseline_check_exe_of[cfg_b]
    odir = oracle_dir(share.oracle_root(args), cfg_b)
    os.makedirs(odir, exist_ok=True)
    counter.idx += 1
    sys.stdout.write(
        f"\r{get_progress_bar(counter.idx, counter.total)} "
        f"CHECK {short_config_label(cfg_b)[:30]:30} | "
        f"{args.baseline_variant:10} | uncompressed (ref data_tab*) "
    )
    sys.stdout.flush()
    try:
        os.remove(os.path.join(odir, ORACLE_MARKER))
    except OSError:
        pass
    ok, _, code, err_tail, _ = run_cmd(
        [exe_b],
        {"OMP_NUM_THREADS": str(args.check_threads)},
        effective_timeout(args.timeout, args.timeout_per_thread, args.check_threads),
        extra_ld_library_path=plan.extra_ldpath, cwd=odir
    )
    if ok:
        # Completeness marker: the gate above only trusts the oracle
        # when this file exists, so an interrupted generation can
        # never be mistaken for a complete one.
        with open(os.path.join(odir, ORACLE_MARKER), "w") as _mf:
            _mf.write(f"generated by {exe_b} (uncompressed), "
                      f"{time.strftime('%Y-%m-%dT%H:%M:%S')}\n")
            # Which binary wrote it: prepare_oracles regenerates the
            # oracle when the config's vector binary changes.
            _mf.write(f"{ORACLE_EXE_KEY}{exe_fingerprint(exe_b)}\n")
        sys.stdout.write(" -> ✅ reference generated\n")
    else:
        sys.stdout.write(f" -> ❌ failed (code {code})\n")
        _entry = (
            f"BASELINE_REF_FAIL: {exe_b} code={code}\n"
            f"  stderr_tail:\n    " + err_tail.replace('\n', '\n    ')
        )
        errors.append(_entry)
        _append_error_now(args.errors_log, _entry)
    sys.stdout.flush()
    return ok


def _check_config(args, plan, counter, errors, cfg):
    """2b for one configuration: each of its check binaries, --reps_check
    times, in its oracle directory."""
    for var in args.variants:
        exe = plan.check_exes.get((cfg, var))
        if not exe:
            continue

        reps_check_this = plan.reps_check_for(cfg)
        success_in_row = 0
        for r in range(reps_check_this):
            counter.idx += 1
            sys.stdout.write(
                f"\r{get_progress_bar(counter.idx, counter.total)} "
                + _prog("CHECK", cyan, cfg, var,
                        th=args.check_threads, run=r + 1,
                        reps=reps_check_this,
                        extra=f"OK:{success_in_row:3} ")
            )
            sys.stdout.flush()

            check_env = {"OMP_NUM_THREADS": str(args.check_threads), **config_env(cfg)}
            check_cwd = oracle_dir(share.oracle_root(args), cfg)
            ok, _, code, err_tail, _ = run_cmd(
                [exe], check_env,
        effective_timeout(args.timeout, args.timeout_per_thread, args.check_threads),
                extra_ld_library_path=plan.extra_ldpath, cwd=check_cwd
            )
            if ok:
                success_in_row += 1
            else:
                _entry = (
                    f"CHECK_FAIL: {exe} iter={r+1} code={code}\n"
                    f"  reproduce: {repro_line([exe], check_env, check_cwd)}\n"
                    f"  stderr_tail:\n    "
                    + err_tail.replace('\n', '\n    ')
                )
                errors.append(_entry)
                _append_error_now(args.errors_log, _entry)
        verdict = f"{success_in_row}/{reps_check_this}"
        if success_in_row == reps_check_this:
            tag = green(f"{verdict} Pass")
        else:
            tag = red(f"{verdict} FAIL")
        sys.stdout.write(f" -> {tag}\n")
        sys.stdout.flush()
